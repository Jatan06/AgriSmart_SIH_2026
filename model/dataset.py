import os
import json
import cv2
import torch
from torch.utils.data import Dataset
import albumentations as A


class AgriDataset(Dataset):
    """
    Custom PyTorch Dataset for agricultural leaf disease images.

    Loads images from disk, converts BGR → RGB, applies the
    albumentations pipeline, and returns (tensor, label) pairs.
    This class itself is stateless with respect to disk layout —
    all scanning logic lives exclusively in build_dataset().
    """

    def __init__(self, image_paths: list[str], labels: list[int], transforms: A.Compose):
        """
        Args:
            image_paths: Absolute paths to all images on disk.
            labels:      Integer encoded class labels (aligned 1-to-1 with image_paths).
            transforms:  An albumentations.Compose pipeline (train or val).
        """
        self.image_paths = image_paths
        self.labels = labels
        self.transforms = transforms

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        image_path = self.image_paths[idx]
        label = self.labels[idx]

        # Read image from disk — OpenCV loads as BGR by default.
        image = cv2.imread(image_path)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # Apply the albumentations pipeline (augmentation + normalisation + ToTensorV2).
        augmented = self.transforms(image=image)
        tensor = augmented["image"]

        return tensor, label

    def __len__(self) -> int:
        return len(self.image_paths)


def build_dataset(dataset_root: str) -> tuple[list, list, int]:
    """
    Scans the dataset folder and builds the image_paths and labels lists.

    CRITICAL RULE: This is the ONLY place in the entire codebase where
    the disk is scanned for class names. Do not duplicate this logic in
    train.py, inference.py, or anywhere else.

    Also auto-generates model/class_names.json from the actual folder
    names found on disk — this file is the single source of truth for
    class-index mapping used by train.py, predict.py, and inference.py.

    Args:
        dataset_root: Absolute path to the dataset root folder.
                      Each immediate subfolder is treated as one class.

    Returns:
        image_paths: List of absolute image paths.
        labels:      List of integer class indices (same order as image_paths).
        num_classes: Total number of classes discovered.
    """
    class_names = sorted(os.listdir(dataset_root))
    image_paths: list[str] = []
    labels: list[int] = []

    for idx, class_name in enumerate(class_names):
        class_dir = os.path.join(dataset_root, class_name)

        # Skip any non-directory entries (e.g. stray files at root level).
        if not os.path.isdir(class_dir):
            continue

        for fname in os.listdir(class_dir):
            if fname.lower().endswith((".jpg", ".jpeg", ".png")):
                image_paths.append(os.path.join(class_dir, fname))
                labels.append(idx)

    # Write class_names.json next to this file (inside model/).
    # DO NOT EDIT THIS FILE MANUALLY — re-run train.py to regenerate.
    json_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "class_names.json")
    with open(json_path, "w") as f:
        json.dump(class_names, f, indent=2)

    return image_paths, labels, len(class_names)